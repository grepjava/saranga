"""Generates crates/saranga-management/src/exceptions.rs: the exception class
each AMQ code of Artemis's message bundles is thrown as, which Jolokia
reports as an operation's error_type.

    python -I scripts/gen-exception-catalog.py

Reads ActiveMQMessageBundle (server) and ActiveMQClientMessageBundle
(client) in reference/activemq-artemis.
"""

import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
REF = ROOT / "reference" / "activemq-artemis"
BUNDLES = [
    REF / "artemis-server/src/main/java/org/apache/activemq/artemis/core/server/ActiveMQMessageBundle.java",
    REF / "artemis-core-client/src/main/java/org/apache/activemq/artemis/core/client/ActiveMQClientMessageBundle.java",
]
OUT = ROOT / "crates/saranga-management/src/exceptions.rs"

MESSAGE = re.compile(r"@Message\(\s*id\s*=\s*(\d+)")
DECLARATION = re.compile(r"^\s*([\w.]+)\s+\w+\s*\(", re.M)


def classes(path):
    text = path.read_text(encoding="utf-8")
    imports = dict(
        (m.group(1).rsplit(".", 1)[1], m.group(1))
        for m in re.finditer(r"^import ([\w.]+);", text, re.M)
    )
    out = {}
    for m in MESSAGE.finditer(text):
        code = int(m.group(1))
        # The declaration after the annotation (whose value may span lines).
        rest = text[m.end():]
        rest = rest[rest.index(")\n") + 2:] if ")\n" in rest else rest
        d = DECLARATION.search(rest)
        if not d:
            continue
        simple = d.group(1)
        if "." in simple:
            fqn = simple
        elif simple in imports:
            fqn = imports[simple]
        else:
            # java.lang (IllegalArgumentException, IllegalStateException...).
            fqn = "java.lang." + simple
        if fqn.startswith("java.lang.") and not simple.endswith(("Exception", "Error")):
            continue  # a String or other message, not thrown
        out[code] = fqn
    return out


def main():
    table = {}
    for b in BUNDLES:
        table.update(classes(b))
    lines = [
        "//! The exception class each AMQ code of Artemis's message bundles is",
        "//! thrown as (`ActiveMQMessageBundle`, `ActiveMQClientMessageBundle`).",
        "//! Generated by scripts/gen-exception-catalog.py; do not edit.",
        "",
        "/// By AMQ code, sorted.",
        "#[rustfmt::skip]",
        "pub static EXCEPTIONS: &[(u32, &str)] = &[",
    ]
    for code in sorted(table):
        lines.append(f'    ({code}, "{table[code]}"),')
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(table)} codes")


main()
